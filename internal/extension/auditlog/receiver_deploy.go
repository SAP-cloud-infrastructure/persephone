package auditlog

import (
	"fmt"

	appsv1 "k8s.io/api/apps/v1"
	corev1 "k8s.io/api/core/v1"
	metav1 "k8s.io/apimachinery/pkg/apis/meta/v1"
	"k8s.io/apimachinery/pkg/util/intstr"
)

const (
	receiverImage     = "persephone-auditlog"
	receiverPort      = 8443
	certMountPath     = "/certs"
	cloudProviderPath = "/cloudprovider"
)

// ReceiverDeployment returns the Deployment for the auditlog receiver in the
// given namespace. image is the full image reference including tag/digest.
// bucket, prefix, and s3Endpoint are passed as flags; prefix may use the shoot name
// already expanded by the caller. tlsSecretName is the versioned name of the
// TLS secret generated by the SecretsManager. objectLock is optional.
func ReceiverDeployment(namespace, image, bucket, prefix, s3Endpoint, tlsSecretName string, objectLock *ObjectLockConfig) *appsv1.Deployment {
	selectorLabels := map[string]string{
		"app":  ReceiverServiceName,
		"role": "auditlog-receiver",
	}
	podLabels := map[string]string{
		"app":  ReceiverServiceName,
		"role": "auditlog-receiver",
		// Allow egress to public networks (OpenStack identity + Swift endpoints).
		"networking.gardener.cloud/to-public-networks": "allowed",
		// Allow egress to DNS for name resolution.
		"networking.gardener.cloud/to-dns": "allowed",
	}

	replicas := int32(1)
	automount := false
	dep := &appsv1.Deployment{}
	dep.APIVersion = "apps/v1"
	dep.Kind = "Deployment"
	dep.Name = ReceiverServiceName
	dep.Namespace = namespace
	dep.Spec = appsv1.DeploymentSpec{
		Replicas: &replicas,
		Selector: &metav1.LabelSelector{MatchLabels: selectorLabels},
		Template: corev1.PodTemplateSpec{
			Spec: corev1.PodSpec{
				AutomountServiceAccountToken: &automount,
				Containers: []corev1.Container{
					{
						Name:    "receiver",
						Image:   image,
						Command: []string{"/usr/bin/persephone-auditlog-receiver"},
						Args:    receiverArgs(bucket, prefix, s3Endpoint, objectLock),
						Ports: []corev1.ContainerPort{
							{Name: "https", ContainerPort: receiverPort, Protocol: corev1.ProtocolTCP},
						},
						Env: []corev1.EnvVar{
							envFromSecret("OS_AUTH_URL", "authURL"),
							envFromSecret("OS_APPLICATION_CREDENTIAL_ID", "applicationCredentialID"),
							envFromSecret("OS_APPLICATION_CREDENTIAL_SECRET", "applicationCredentialSecret"),
							envFromSecret("OS_S3_ACCESS_KEY", "ec2AccessKey"),
							envFromSecret("OS_S3_SECRET_KEY", "ec2SecretKey"),
						},
						VolumeMounts: []corev1.VolumeMount{
							{
								Name:      "receiver-tls",
								MountPath: certMountPath,
								ReadOnly:  true,
							},
						},
					},
				},
				Volumes: []corev1.Volume{
					{Name: "receiver-tls", Secret: &corev1.SecretVolumeSource{SecretName: tlsSecretName}},
				},
			},
		},
	}
	dep.Spec.Template.Labels = podLabels
	return dep
}

func receiverArgs(bucket, prefix, s3Endpoint string, objectLock *ObjectLockConfig) []string {
	args := []string{
		"--addr=:8443",
		"--cert-dir=" + certMountPath,
		"--bucket=" + bucket,
		"--prefix=" + prefix,
	}
	if s3Endpoint != "" {
		args = append(args, "--s3-endpoint="+s3Endpoint)
	}
	if objectLock != nil && objectLock.Enabled {
		args = append(args, "--object-lock")
		args = append(args, fmt.Sprintf("--object-lock-retention-days=%d", objectLock.RetentionDays))
		args = append(args, "--object-lock-mode="+objectLock.Mode)
	}
	return args
}

// ReceiverService returns the ClusterIP Service for the auditlog receiver.
func ReceiverService(namespace string) *corev1.Service {
	labels := map[string]string{
		"app":  ReceiverServiceName,
		"role": "auditlog-receiver",
	}
	svc := &corev1.Service{}
	svc.APIVersion = "v1"
	svc.Kind = "Service"
	svc.Name = ReceiverServiceName
	svc.Namespace = namespace
	svc.Spec = corev1.ServiceSpec{
		Selector: labels,
		Ports: []corev1.ServicePort{
			{
				Name:       "https",
				Port:       443,
				TargetPort: intstr.FromInt32(receiverPort),
				Protocol:   corev1.ProtocolTCP,
			},
		},
	}
	return svc
}

func envFromSecret(envName, key string) corev1.EnvVar {
	ref := &corev1.SecretKeySelector{Key: key}
	ref.Name = "cloudprovider"
	return corev1.EnvVar{
		Name:      envName,
		ValueFrom: &corev1.EnvVarSource{SecretKeyRef: ref},
	}
}
