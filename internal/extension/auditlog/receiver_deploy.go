package auditlog

import (
	appsv1 "k8s.io/api/apps/v1"
	corev1 "k8s.io/api/core/v1"
	metav1 "k8s.io/apimachinery/pkg/apis/meta/v1"
	"k8s.io/apimachinery/pkg/util/intstr"
	"k8s.io/utils/ptr"
)

const (
	receiverImage     = "keppel.eu-de-1.cloud.sap/ccloud/persephone-auditlog-receiver"
	receiverPort      = 8443
	certMountPath     = "/certs"
	cloudProviderPath = "/cloudprovider"
)

// ReceiverDeployment returns the Deployment for the auditlog receiver in the
// given namespace. image is the full image reference including tag/digest.
// container and prefix are passed as flags; prefix may use the shoot name
// already expanded by the caller. tlsSecretName is the versioned name of the
// TLS secret generated by the SecretsManager.
func ReceiverDeployment(namespace, image, container, prefix, tlsSecretName string) *appsv1.Deployment {
	selectorLabels := map[string]string{
		"app":  ReceiverServiceName,
		"role": "auditlog-receiver",
	}
	podLabels := map[string]string{
		"app":  ReceiverServiceName,
		"role": "auditlog-receiver",
		// Allow egress to public networks (OpenStack identity + Swift endpoints).
		"networking.gardener.cloud/to-public-networks": "allowed",
		// Allow egress to DNS for name resolution.
		"networking.gardener.cloud/to-dns": "allowed",
	}

	return &appsv1.Deployment{
		TypeMeta: metav1.TypeMeta{
			APIVersion: "apps/v1",
			Kind:       "Deployment",
		},
		ObjectMeta: metav1.ObjectMeta{
			Name:      ReceiverServiceName,
			Namespace: namespace,
		},
		Spec: appsv1.DeploymentSpec{
			Replicas: ptr.To(int32(1)),
			Selector: &metav1.LabelSelector{MatchLabels: selectorLabels},
			Template: corev1.PodTemplateSpec{
				ObjectMeta: metav1.ObjectMeta{Labels: podLabels},
				Spec: corev1.PodSpec{
					AutomountServiceAccountToken: ptr.To(false),
					Containers: []corev1.Container{
						{
							Name:  "receiver",
							Image: image,
							Command: []string{"/usr/bin/persephone-auditlog-receiver"},
							Args: []string{
								"--addr=:8443",
								"--cert-dir=" + certMountPath,
								"--container=" + container,
								"--prefix=" + prefix,
							},
							Ports: []corev1.ContainerPort{
								{Name: "https", ContainerPort: receiverPort, Protocol: corev1.ProtocolTCP},
							},
							Env: []corev1.EnvVar{
								envFromSecret("OS_AUTH_URL", "cloudprovider", "authURL"),
								envFromSecret("OS_APPLICATION_CREDENTIAL_ID", "cloudprovider", "applicationCredentialID"),
								envFromSecret("OS_APPLICATION_CREDENTIAL_SECRET", "cloudprovider", "applicationCredentialSecret"),
							},
							VolumeMounts: []corev1.VolumeMount{
								{
									Name:      "receiver-tls",
									MountPath: certMountPath,
									ReadOnly:  true,
								},
							},
						},
					},
					Volumes: []corev1.Volume{
						{
							Name: "receiver-tls",
							VolumeSource: corev1.VolumeSource{
								Secret: &corev1.SecretVolumeSource{
									SecretName: tlsSecretName,
								},
							},
						},
					},
				},
			},
		},
	}
}

// ReceiverService returns the ClusterIP Service for the auditlog receiver.
func ReceiverService(namespace string) *corev1.Service {
	labels := map[string]string{
		"app":  ReceiverServiceName,
		"role": "auditlog-receiver",
	}
	return &corev1.Service{
		TypeMeta: metav1.TypeMeta{
			APIVersion: "v1",
			Kind:       "Service",
		},
		ObjectMeta: metav1.ObjectMeta{
			Name:      ReceiverServiceName,
			Namespace: namespace,
		},
		Spec: corev1.ServiceSpec{
			Selector: labels,
			Ports: []corev1.ServicePort{
				{
					Name:       "https",
					Port:       443,
					TargetPort: intstr.FromInt32(receiverPort),
					Protocol:   corev1.ProtocolTCP,
				},
			},
		},
	}
}

func envFromSecret(envName, secretName, key string) corev1.EnvVar {
	return corev1.EnvVar{
		Name: envName,
		ValueFrom: &corev1.EnvVarSource{
			SecretKeyRef: &corev1.SecretKeySelector{
				LocalObjectReference: corev1.LocalObjectReference{Name: secretName},
				Key:                  key,
			},
		},
	}
}
